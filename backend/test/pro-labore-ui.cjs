const { chromium } = require('playwright');
const fs = require('node:fs'), path = require('node:path'), http = require('node:http');
const assert = require('node:assert/strict');
const parsePdf = require('pdf-parse');
async function main() {
  const root = path.resolve(__dirname, '../../frontend/dist');
  const output = path.resolve(__dirname, '../../tmp/pro-labore'); fs.mkdirSync(output, { recursive: true });
  const server = http.createServer((req, res) => {
    const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    const file = pathname.startsWith('/assets/') || pathname.startsWith('/content/') ? path.join(root, pathname) : path.join(root, 'index.html');
    if (!file.startsWith(root) || !fs.existsSync(file)) { res.writeHead(404); return res.end(); }
    res.setHeader('Content-Type', { '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.woff2': 'font/woff2', '.woff': 'font/woff' }[path.extname(file)] || 'text/html');
    res.end(fs.readFileSync(file));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
    const errors = [], apiRequests = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', route => { apiRequests.push(route.request().url()); return route.fulfill({ status: 401, json: { error: 'expired' } }); });
    const origin = process.env.TEST_BASE_URL || `http://127.0.0.1:${server.address().port}`;
    await page.goto(origin + '/calculadora-pro-labore');
    await page.getByRole('heading', { name: 'Calculadora de pró-labore', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.length), 0);
    const search = page.getByRole('searchbox', { name: 'Buscar atividade ou CNAE' });
    for (const code of ['9602501', '9602-5/01']) {
      await search.fill(code);
      assert.equal(await page.getByLabel('Atividade exercida').inputValue(), 'hairdressing');
      await page.getByText('Anexo III', { exact: true }).waitFor();
      assert.equal(await page.getByRole('spinbutton', { name: /^Folha com encargos/ }).count(), 0);
    }
    await search.fill('0111301');
    assert.equal(await page.getByLabel('Atividade exercida').inputValue(), 'cnae:0111301');
    await page.getByText('Atividade identificada · enquadramento a confirmar', { exact: true }).waitFor();
    await search.fill('9999999');
    assert.equal(await page.getByLabel('Atividade exercida').inputValue(), '');
    await search.fill('');
    await page.getByLabel('Atividade exercida').selectOption('training');
    await page.getByRole('spinbutton', { name: /^Receita bruta/ }).fill('120000');
    await page.getByRole('checkbox', { name: /13 meses/ }).check();
    await page.getByRole('checkbox', { name: /integralmente/ }).check();
    await page.getByRole('button', { name: 'Continuar' }).click();
    await page.getByRole('spinbutton', { name: /^Pró-labore bruto mensal/ }).fill('3000');
    await page.getByRole('button', { name: 'Calcular simulação' }).click();
    await page.getByTestId('revenue').waitFor();
    assert.match(await page.getByTestId('revenue').textContent(), /3\.191,49/);
    assert.equal(await page.getByTestId('company-revenue').textContent(), await page.getByTestId('revenue').textContent());
    assert.ok(await page.getByTestId('company-revenue').evaluate(element => element.closest('.pl-breakdown').textContent.includes('Empresa')));
    assert.match(await page.getByTestId('net').textContent(), /2\.670,00/);
    assert.match(await page.getByTestId('individual-taxes').textContent(), /330,00/);
    assert.ok(await page.getByTestId('individual-taxes').evaluate(element => element.closest('.pl-breakdown').textContent.includes('Sócio')));
    assert.match(await page.getByTestId('total-taxes').textContent(), /521,49/);
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Baixar simulação em PDF' }).click();
    const downloaded = await download;
    assert.equal(downloaded.suggestedFilename(), 'simulacao-pro-labore-2026.pdf');
    const bytes = fs.readFileSync(await downloaded.path()); fs.writeFileSync(path.join(output, 'simulacao.pdf'), bytes);
    const parsed = await parsePdf(bytes);
    assert.ok(parsed.numpages >= 2); assert.match(parsed.text, /3\.191,49/); assert.match(parsed.text, /521,49/); assert.match(parsed.text, /Premissas/); assert.match(parsed.text, /Fontes oficiais/);
    assert.match(parsed.text, /TOTAL DE IMPOSTOS DO SÓCIO \(INSS \+ IRRF\): R\$ 330,00/);
    await page.getByRole('spinbutton', { name: /^Pró-labore bruto mensal/ }).fill('6000');
    assert.equal(await page.getByTestId('revenue').count(), 0);
    await page.getByRole('tab', { name: 'Atividade da empresa' }).click();
    await page.getByRole('searchbox', { name: 'Buscar atividade ou CNAE' }).fill('7020-4/00');
    await page.getByLabel('Atividade exercida').selectOption('consulting');
    await page.getByRole('button', { name: 'Continuar' }).click();
    await page.getByRole('button', { name: 'Calcular simulação' }).click();
    await page.getByRole('alert').filter({ hasText: /Folha/ }).waitFor();
    await page.getByRole('tab', { name: 'Atividade da empresa' }).click();
    await page.getByRole('spinbutton', { name: /^Folha com encargos/ }).fill('33599.99');
    await page.getByRole('button', { name: 'Continuar' }).click();
    await page.getByRole('button', { name: 'Calcular simulação' }).click();
    await page.getByText('Anexo V · 15,5%', { exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Atividade da empresa' }).click();
    await page.getByRole('spinbutton', { name: /^Folha com encargos/ }).fill('33600');
    await page.getByRole('button', { name: 'Continuar' }).click();
    await page.getByRole('button', { name: 'Calcular simulação' }).click();
    await page.getByText('Anexo III · 6%', { exact: true }).waitFor();
    assert.match(await page.getByTestId('individual-taxes').textContent(), /1\.040,02/);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    await page.getByRole('tab', { name: 'Atividade da empresa' }).click();
    await page.getByRole('spinbutton', { name: /^Receita bruta/ }).fill('180000.01');
    await page.getByRole('button', { name: 'Continuar' }).click();
    await page.getByRole('button', { name: 'Calcular simulação' }).click();
    await page.getByRole('alert').filter({ hasText: /ultrapassa/ }).waitFor();
    assert.equal(await page.getByTestId('revenue').count(), 0);
    await page.getByRole('button', { name: 'Limpar dados' }).click();
    assert.equal(await page.getByLabel('Atividade exercida').inputValue(), '');
    await page.evaluate(() => { localStorage.setItem('token', 'expired'); localStorage.setItem('user', '{broken-json'); });
    await page.goto(origin + '/Calculadora-Pro-Labore/'); await page.getByRole('heading', { name: 'Calculadora de pró-labore', exact: true }).waitFor();
    assert.equal(apiRequests.length, 0, 'public calculator must never call private APIs, even with an expired token');
    assert.equal(await page.evaluate(() => localStorage.getItem('token')), 'expired');
    await page.evaluate(() => localStorage.clear());
    await page.goto(origin + '/financeiro'); await page.waitForURL('**/login');
    assert.deepEqual(errors, []);
    console.log('PASS: public no-login access, stale-session isolation, activities/CNAE, factor R threshold, cash totals, PDF text/pages, invalidation, mobile, private route protection');
  } finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
